def _key_co(obj, key):
    n = len(obj.data.vertices)
    a = np.empty(n * 3); key.data.foreach_get("co", a)
    return a.reshape(-1, 3)


def _target_delta(bm, basis, name):
    path = TargetService.target_full_path(name)
    assert path and os.path.basename(path).startswith(name + ".target"), (name, path)
    k = TargetService.load_target(bm, path, weight=0.0, name="__tmp_cust")
    d = _key_co(bm, k) - basis
    bm.shape_key_remove(k)
    return d


def _macro_delta(bm, basis, changes):
    """Mesh delta (basemesh local, all vertices incl. helpers) of changing MakeHuman macros from the preset's values
    to `changes`, using MPFB's own macro-target interpolation (the same stack reapply_macro_details would load)."""
    info = TargetService.get_macro_info_dict_from_basemesh(bm)
    mod = copy.deepcopy(info); mod.update(changes)
    a = {t: w for t, w in TargetService.calculate_target_stack_from_macro_info_dict(info, cutoff=0.0)}
    b = {t: w for t, w in TargetService.calculate_target_stack_from_macro_info_dict(mod, cutoff=0.0)}
    D = np.zeros_like(basis)
    for t in set(a) | set(b):
        dw = b.get(t, 0.0) - a.get(t, 0.0)
        if abs(dw) < 1e-7:
            continue
        path = os.path.join(MPFB_TARGETS, t + ".target.gz")
        k = TargetService.load_target(bm, path, weight=0.0, name="__tmp_macro")
        D += dw * (_key_co(bm, k) - basis)
        bm.shape_key_remove(k)
    return D


def _expand(side):
    return ["l-" + side[3:], "r-" + side[3:]] if side.startswith("LR:") else [side]


def slider_deltas(bm, basis, kind, neg, pos):
    """(neg delta, pos delta, preset modifier value). Target sliders map s = +-1 to MakeHuman's full modifier range
    RELATIVE TO THE PRESET: if the preset already uses the pair at modifier value m0 (incr weight a = max(m0, 0),
    decr weight b = max(-m0, 0)), then pos = (1 - a) * incr - b * decr and neg = (1 - b) * decr - a * incr, so the
    base + any slider value stays inside MakeHuman's authored [-1, 1] range (no double-dipping)."""
    if isinstance(pos, dict):
        return (_macro_delta(bm, basis, neg) if neg else None), _macro_delta(bm, basis, pos), None
    pv = PRESETS[kind]["targets"]
    P = _expand(pos); N = _expand(neg) if neg else [None] * len(P)
    Dp = np.zeros_like(basis); Dn = np.zeros_like(basis) if neg else None
    m0s = []
    for n, p in zip(N, P):
        dp = _target_delta(bm, basis, p)
        dn = _target_delta(bm, basis, n) if n else 0.0
        m0 = pv.get(p, 0.0) - (pv.get(n, 0.0) if n else 0.0)
        a, b = max(m0, 0.0), max(-m0, 0.0)
        Dp += (1 - a) * dp - b * dn
        if n:
            Dn += (1 - b) * dn - a * dp
        m0s.append(m0)
    return Dn, Dp, round(float(np.mean(m0s)), 3)


PRESET_MOD = {}


def add_cust_keys(bm, kind):
    """Adds every cust_* morph to the live basemesh as a shape key (value 0). Returns {morph: stats}."""
    kb = bm.data.shape_keys.key_blocks
    basis = _key_co(bm, kb["Basis"])
    stats = {}
    t0 = time.time()
    for sid, grp, lab, neg, pos, rnd in sliders_for(kind):
        Dn, Dp, m0 = slider_deltas(bm, basis, kind, neg, pos)
        PRESET_MOD[sid] = m0
        for suffix, D in (("_neg", Dn), ("_pos", Dp)):
            if D is None:
                continue
            name = CUST + sid + suffix
            sk = bm.shape_key_add(name=name, from_mix=False)
            sk.data.foreach_set("co", (basis + D).ravel())
            sk.value = 0.0
            mag = np.linalg.norm(D[:NBODY], axis=1)
            stats[name] = dict(verts=int((mag > 1e-6).sum()), max_mm=round(float(mag.max()) * 1000, 2),
                               feet_mm=round(float(D[:NBODY][basis[:NBODY, 2] < basis[:NBODY, 2].min() + 0.02, 2].mean()) * 1000, 2))
    log("cust keys: %d morphs in %.1fs" % (len(stats), time.time() - t0))
    return stats


def interpolate_keys_to_parts(rig, bm, names, min_shift=1e-4):
    """Barycentric mhclo interpolation of basemesh shape keys onto every child part (brows, lashes, eyes, teeth, tongue,
    hair, beards), as FaceService.interpolate_targets does for the ARKit keys; offsets < 0.1 mm are dropped (sparse)."""
    kb = bm.data.shape_keys.key_blocks
    basis = _key_co(bm, kb["Basis"])
    deltas = {n: _key_co(bm, kb[n]) - basis for n in names if n in kb}
    for child in children_meshes(rig):
        if child == bm:
            continue
        path = ClothesService.find_clothes_absolute_path(child)
        if not path:
            continue
        mh = Mhclo(); mh.load(path)
        n = len(child.data.vertices)
        idx = np.zeros((n, 3), dtype=np.int64); w = np.zeros((n, 3))
        for vi, m in mh.verts.items():
            if vi < n:
                idx[vi] = m["verts"]; w[vi] = m["weights"]
        if not child.data.shape_keys:
            child.shape_key_add(name="Basis", from_mix=False)
        cb = _key_co(child, child.data.shape_keys.key_blocks["Basis"])
        added = 0
        for name, D in deltas.items():
            if name in child.data.shape_keys.key_blocks:
                continue
            d = (D[idx] * w[:, :, None]).sum(1)
            d[np.linalg.norm(d, axis=1) < min_shift] = 0.0
            if not d.any():
                continue
            sk = child.shape_key_add(name=name, from_mix=False)
            sk.data.foreach_set("co", (cb + d).ravel()); sk.value = 0.0
            added += 1
        log("  cust -> %-26s %3d morphs" % (child.name, added))


def bone_offsets(rig, bm, names, eps=2e-4):
    """How each cust morph moves the rts_human joints (MPFB rig strategies = joint cubes / vertex means evaluated on the
    morphed basemesh). Returns {morph: {bone: [dx, dy, dz]}} in glTF space (+Y up, +Z forward), metres, >= 0.2 mm."""
    rig_file = [r["path"] for r in AssetService.get_custom_rigs(use_cache=False) if r["name"] == RIG_NAME.split(".", 1)[1]][0]
    kb = bm.data.shape_keys.key_blocks
    for k in kb:
        if k.name in FACE_KEYS or k.name.startswith(CUST):
            k.value = 0.0
    # face_lib's 'rts_face_fix' modelling key (lip seal, < 1 mm) was added after the rig was fitted: mute it while the
    # strategies are evaluated so they reproduce the rest skeleton (the offsets are differences, it does not matter)
    muted = {k.name: k.value for k in kb if k.name == "rts_face_fix"}
    for n in muted:
        kb[n].value = 0.0

    def heads():
        r = Rig.from_json_file_and_basemesh(rig_file, bm)
        return {b: np.array(r.get_best_location_from_strategy(info["head"])) for b, info in r.rig_definition.items()}
    t0 = time.time()
    h0 = heads()
    rest = {b.name: np.array(b.head_local) for b in rig.data.bones}
    err = max(np.abs(h0[b] - rest[b]).max() for b in rest)
    assert err < 1e-4, "rig strategies do not reproduce the rest skeleton (%.2e m)" % err
    out = {}
    for name in names:
        kb[name].value = 1.0
        h = heads()
        kb[name].value = 0.0
        d = {}
        for b in rest:
            v = h[b] - h0[b]
            if np.abs(v).max() >= eps:
                d[b] = [round(float(v[0]), 5), round(float(v[2]), 5), round(float(-v[1]), 5)]   # Blender Z-up -> glTF Y-up
        out[name] = d
    for n, v in muted.items():
        kb[n].value = v
    log("bone offsets for %d morphs in %.1fs (max %d bones moved)" % (len(names), time.time() - t0,
                                                                     max(len(v) for v in out.values())))
    return out


