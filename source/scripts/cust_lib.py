def sparsify_card_keys(obj, eps=3e-4):
    """Hair / beard / brow / lash cards: zero per-vertex morph offsets below eps (0.3 mm, invisible on cards) so the
    glTF sparse accessors stay small; keys left empty are removed. Returns (keys removed, offsets zeroed)."""
    if not obj.data.shape_keys:
        return 0, 0
    kb = obj.data.shape_keys.key_blocks
    base = _key_co(obj, kb["Basis"])
    removed = zeroed = 0
    for k in list(kb)[1:]:
        d = _key_co(obj, k) - base
        small = np.linalg.norm(d, axis=1) < eps
        nz = np.abs(d).max(1) > 0
        zeroed += int((small & nz).sum())
        d[small] = 0.0
        if not d.any():
            obj.shape_key_remove(k); removed += 1
            continue
        k.data.foreach_set("co", (base + d).ravel())
    if len(obj.data.shape_keys.key_blocks) == 1:
        obj.shape_key_clear()
    return removed, zeroed


def ground_export(rig, kind):
    """Engine export only (after the live .blend is saved): put the soles on the ground. MPFB grounds the macro body,
    so detail targets that shorten the legs (proportion variants: male_stocky) leave the feet floating. Shifts every
    mesh (vertices + all shape keys) and every bone by the same -z (the ground 'root' joint goes to z = 0)."""
    body = find_part(rig, "_body")
    kb = body.data.shape_keys.key_blocks if body.data.shape_keys else None
    co = _key_co(body, kb["Basis"]) if kb else np.array([v.co[:] for v in body.data.vertices])
    z0 = float(co[:, 2].min())
    if abs(z0) < 1e-4:
        return 0.0
    for o in children_meshes(rig):
        n = len(o.data.vertices)
        a = np.empty(n * 3); o.data.vertices.foreach_get("co", a); a = a.reshape(-1, 3); a[:, 2] -= z0
        o.data.vertices.foreach_set("co", a.ravel())
        if o.data.shape_keys:
            for k in o.data.shape_keys.key_blocks:
                b = _key_co(o, k); b[:, 2] -= z0; k.data.foreach_set("co", b.ravel())
        o.data.update()
    bpy.context.view_layer.objects.active = rig
    for ob in bpy.context.selected_objects:
        ob.select_set(False)
    rig.select_set(True)
    bpy.ops.object.mode_set(mode='EDIT')
    for eb in rig.data.edit_bones:
        dz = z0 if eb.name != "root" else eb.head.z
        eb.head.z -= dz; eb.tail.z -= dz
    bpy.ops.object.mode_set(mode='OBJECT')
    log("%s grounded: soles were %.1f mm above the floor" % (kind, z0 * 1000))
    return z0
