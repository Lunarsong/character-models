def _variant_preset(name, spec):
    p = copy.deepcopy(PRESETS[spec["base"]])
    p["tex_kind"] = spec["base"]
    p["stature"] = spec["stature"]
    p["phenotype"].update(spec["phenotype"])
    for t, v in spec["add_targets"].items():
        if v < 0:      # negative = remove / reduce a preset target
            p["targets"][t] = max(0.0, p["targets"].get(t, 0.0) + v)
        else:
            p["targets"][t] = p["targets"].get(t, 0.0) + v
    p["targets"] = {k: v for k, v in p["targets"].items() if v > 0}
    return p


