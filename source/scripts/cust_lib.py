def _default_colour(kind):
    """The HAIR_COLOURS entry of the preset's hair colour (nearest one if the preset was re-tuned)."""
    rgb = np.array(PRESETS[kind]["hair_rgb"])
    return min(HAIR_COLOURS, key=lambda nc: float(np.abs(np.array(nc[1]) - rgb).sum()))[0]


def parts_catalogue(rig, kind):
    cat = {"hair": [], "beard": [{"style": "none", "node": None, "default": True}], "eyebrows": [], "eyelashes": []}
    for o in children_meshes(rig):
        role = o.get("rts_part")
        if role in cat:
            cat[role].append({"style": o.get("rts_style"), "node": o.name, "default": bool(o.get("rts_default")),
                              "file": "parts_%s.glb" % kind if o.get("rts_alt") else "base_%s.glb" % kind})
    cat["hair"].append({"style": "none", "node": None, "default": False})
    for v in cat.values():
        v.sort(key=lambda e: (not e["default"], e["style"] == "none", e["style"]))
    return cat


def variant_spec(rig, kind, for_parts):
    """KHR_materials_variants options (glb_post.py) for the base GLB (skin, eyes, hair colour on the default hair and
    brows) or for the parts GLB (hair colour on the alternate hair / beards / brows)."""
    p = PRESETS[kind]
    tk = p.get("tex_kind", kind)
    dcol = _default_colour(kind)
    V = []
    if not for_parts:
        for tone, mix, _ in SKIN_TONES[tk]:
            V.append({"name": "skin:" + tone, "materials": {"M_%s_skin" % kind: {} if mix is None else
                      {"baseColorTexture": os.path.join(TEX, "%s_skin_%s_base.jpg" % (tk, tone))}}})
        for tone, f in SKIN_TINTS:
            V.append({"name": "skin:" + tone, "materials": {"M_%s_skin" % kind: {"baseColorFactor": list(f) + [1.0]}}})
        for c in EYE_COLOURS:
            V.append({"name": "eyes:" + c, "materials": {"M_%s_eye" % kind: {} if c == p["eye_color"] else
                      {"baseColorTexture": os.path.join(PARTS_TEX, "eye_%s.jpg" % c)}}})
    dhair = p["parts"]["hair"].split("/")[0]
    neutral_default = os.path.join(TEX, "hair_strands_neutral_base.png") if dhair.startswith("rts_") else \
        os.path.join(PARTS_TEX, "hair_%s.png" % dhair)
    for cname, rgb in HAIR_COLOURS:
        mats = {}
        for o in children_meshes(rig):
            if bool(o.get("rts_alt")) != for_parts or not o.data.materials:
                continue
            role = o.get("rts_part")
            if role not in ("hair", "beard", "eyebrows"):
                continue
            if cname == dcol:
                ov = {}
            elif role in ("hair", "beard"):
                ov = {"baseColorFactor": hair_factor(rgb) + [1.0]}
                if not for_parts:                      # the default hair ships the coloured atlas: swap to neutral
                    ov["baseColorTexture"] = neutral_default
            else:
                ov = {"baseColorFactor": brow_factor(rgb) + [1.0]}
            for mat in o.data.materials:               # card beards: cards + their shadow shell
                # scalp caps (hair_lib.join_caps, '<hair material>_cap'): own neutral texture, recoloured by the factor
                mats[mat.name] = {a: b for a, b in ov.items() if a != "baseColorTexture"} if mat.name.endswith("_cap") else ov
        V.append({"name": "hair:" + cname, "materials": mats})
    return V


